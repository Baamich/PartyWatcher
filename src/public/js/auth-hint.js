// Главная: уже вошедший видит экран входа, пока не ответит /auth/me, — и страница «прыгает».
// Подключается в <head> до отрисовки: если в прошлый раз вход был, сразу показываем приложение,
// а index.js после ответа сервера исправит, если подсказка ошиблась (вышел на другой вкладке, истёк вход).
(function () {
  try {
    if (localStorage.getItem('pw_authed') === '1') document.documentElement.classList.add('pw-authed');
  } catch (_) {
    // приватный режим без localStorage — просто без подсказки
  }
})();
